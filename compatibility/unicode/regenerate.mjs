// Development-only regeneration from exact, previously acquired official bytes.
// Compiler builds and ordinary tests use the committed data and never run this.
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

assert.equal(process.argv.length, 4, 'Usage: node compatibility/unicode/regenerate.mjs --source DIRECTORY');
assert.equal(process.argv[2], '--source');
const destination = fileURLToPath(new URL('.', import.meta.url));
const provenance = JSON.parse(readFileSync(join(destination, 'provenance.json'), 'utf8'));
const source = new Map();
for (const item of provenance.sources) {
  const bytes = readFileSync(join(process.argv[3], item.file));
  assert.equal(bytes.length, item.byte_length, item.file + ': byte length');
  assert.equal(createHash('sha256').update(bytes).digest('hex'), item.sha256, item.file + ': SHA-256');
  source.set(item.file, bytes.toString('utf8'));
}
assert.match(source.get('unicodedata_db.h'), /#define UNIDATA_VERSION "17\.0\.0"/);
assert.ok(source.get('lexical_analysis.rst').includes('/Public/17.0.0/ucd/DerivedCoreProperties.txt'));

const header = '# Derived from Unicode 17.0.0 official data. Copyright 2025 Unicode, Inc.\n# See LICENSE-UNICODE.txt and provenance.json.\n';
const ranges = [];
for (const line of source.get('DerivedCoreProperties.txt').split('\n')) {
  const match = /^([A-F0-9]+)(?:\.\.([A-F0-9]+))?\s*;\s*(XID_Start|XID_Continue)\s*(?:#|$)/.exec(line);
  if (match) ranges.push(match[3] + ';' + match[1] + ';' + (match[2] ?? match[1]));
}
assert.ok(ranges.length > 1000);
writeFileSync(join(destination, 'xid-ranges-17.0.0.txt'), header + ranges.join('\n') + '\n');

const vectors = [];
let rows = 0;
for (const raw of source.get('NormalizationTest.txt').split('\n')) {
  const line = raw.split('#', 1)[0].trim();
  if (!line) continue;
  if (/^@Part\d+$/.test(line)) {
    vectors.push(line);
    continue;
  }
  const columns = line.split(';');
  assert.equal(columns.length, 6, 'Normalization vector has five columns and trailing semicolon');
  assert.equal(columns.pop().trim(), '');
  assert.ok(columns.every(column => /^[A-F0-9 ]+$/.test(column.trim())));
  vectors.push(columns.map(column => column.trim()).join(';'));
  rows++;
}
assert.ok(rows > 19000);
writeFileSync(join(destination, 'normalization-17.0.0.txt'), header + vectors.join('\n') + '\n');
writeFileSync(join(destination, 'LICENSE-UNICODE.txt'), source.get('UNICODE-LICENSE.txt'));
for (const item of provenance.generated_fixtures) {
  const bytes = readFileSync(join(destination, item.file));
  assert.equal(bytes.length, item.byte_length, item.file + ': generated byte length');
  assert.equal(createHash('sha256').update(bytes).digest('hex'), item.sha256, item.file + ': generated SHA-256');
}
console.log(JSON.stringify({ unicode: provenance.unicode_version, xid_ranges: ranges.length, normalization_vectors: rows, source_hashes_verified: provenance.sources.length }));
