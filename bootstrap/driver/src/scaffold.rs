//! Exclusive new-leaf project creation. No process execution or dependency setup.

use naja_frontend::Dialect;
use naja_seed::{check_with_dialect, manifest::parse_manifest};
use std::{
    fs::{self, Metadata, OpenOptions},
    io::{self, Write},
    path::{Component, Path, PathBuf},
};

pub const INIT_PATH_MAX_BYTES: usize = 32 * 1024;
pub const INIT_PATH_COMPONENT_LIMIT: usize = 128;
pub const INIT_PARENT_COMPONENT_MAX_BYTES: usize = 255;
pub const INIT_NAME_MAX_BYTES: usize = 128;
pub const INIT_FILE_MAX_BYTES: usize = 4096;
const FILENAMES: [&str; 3] = ["naja.toml", "main.naja", "test_smoke.naja"];

const MAIN_SOURCE: &str = "# Minimal hosted NAJA program.\ndef answer():\n    return 6 * 7\n\nvalue = answer()\nassert value == 42\nprint(value)\n";
const SMOKE_SOURCE: &str = "# Program-file smoke test, not test-function discovery or imports.\ndef add(left, right):\n    return left + right\n\nassert add(20, 22) == 42\nassert len(\"NAJA\") == 4\nassert (\"na\" + \"ja\") == \"naja\"\nassert 12345678901234567890 + 1 == 12345678901234567891\n";

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct InitSummary {
    pub name: String,
    /// Relative generated names only; no private absolute directory inventory.
    pub created_files: Vec<String>,
}

struct Destination {
    requested_parent: PathBuf,
    parent: PathBuf,
    target: PathBuf,
    name: String,
}

struct Generated {
    name: String,
    contents: [String; 3],
}

/// Create a previously absent leaf under an existing ordinary local parent.
/// Generated bytes pass the shared parser/checker before the first write. Any
/// partial I/O failure retains owned output for inspection, never rolls it back.
/// Path checks assume a stable tree; they do not establish hostile-race confinement.
pub fn init_project(path: &Path) -> Result<InitSummary, String> {
    let destination = destination(path)?;
    let generated = generate(&destination.name)?;
    ensure_parent(&destination)?;
    create_directory(&destination.target).map_err(|error| {
        io_failure(
            "cannot exclusively create the new leaf directory",
            None,
            &error,
            false,
        )
    })?;
    write_generated_files(&destination, &generated)?;
    Ok(InitSummary {
        name: generated.name,
        created_files: FILENAMES.iter().map(|name| (*name).to_owned()).collect(),
    })
}

fn create_directory(path: &Path) -> io::Result<()> {
    #[cfg(unix)]
    {
        use std::os::unix::fs::DirBuilderExt;
        fs::DirBuilder::new().mode(0o700).create(path)
    }
    #[cfg(not(unix))]
    {
        fs::create_dir(path)
    }
}

fn generate(name: &str) -> Result<Generated, String> {
    // Component validation rejects quotes, backslashes and controls, so this
    // quoted Unicode data cannot terminate a TOML string or inject a declaration.
    validate_component(name, INIT_NAME_MAX_BYTES)?;
    let manifest = format!(
        "schema = 1\n\n[project]\nname = \"{name}\"\ndialect = \"naja\"\nedition = \"2026.1\"\nprofile = \"hosted\"\nentry = \"main.naja\"\ntarget = \"x86_64-unknown-linux-gnu\"\n"
    );
    let contents = [manifest, MAIN_SOURCE.to_owned(), SMOKE_SOURCE.to_owned()];
    if contents
        .iter()
        .any(|source| source.len() > INIT_FILE_MAX_BYTES)
    {
        return Err(
            "NJA040: generated file exceeds the fixed 4096-byte budget; no project was created"
                .into(),
        );
    }
    parse_manifest(&contents[0]).map_err(|_| {
        "NJA040: generated manifest validation failed; no project was created".to_owned()
    })?;
    for source in &contents[1..] {
        check_with_dialect(source, Dialect::Naja2026).map_err(|_| {
            "NJA040: generated source validation failed; no project was created".to_owned()
        })?;
    }
    Ok(Generated {
        name: name.to_owned(),
        contents,
    })
}

fn destination(path: &Path) -> Result<Destination, String> {
    let raw = path
        .to_str()
        .ok_or("NJA040: project path must be valid UTF-8; no project was created")?;
    if raw.is_empty() || raw.len() > INIT_PATH_MAX_BYTES {
        return Err(
            "NJA040: project path must contain 1..32768 UTF-8 bytes; no project was created".into(),
        );
    }
    if matches!(raw.rsplit(['/', '\\']).next(), None | Some("" | "." | "..")) {
        return Err(
            "NJA040: project path must end in a new normal leaf name; no project was created"
                .into(),
        );
    }
    // Do this before joining: verbatim Windows PathBuf joins can normalize .. .
    check_components(path)?;
    let absolute = if path.is_absolute() {
        path.to_owned()
    } else {
        std::env::current_dir()
            .map_err(|error| {
                io_failure(
                    "cannot resolve the relative project path",
                    None,
                    &error,
                    false,
                )
            })?
            .join(path)
    };
    if !absolute.is_absolute() {
        return Err(
            "NJA040: project path must resolve to an absolute local path; no project was created"
                .into(),
        );
    }
    check_path_budget(&absolute)?;
    let name = absolute
        .file_name()
        .and_then(|value| value.to_str())
        .ok_or("NJA040: project path must name a new UTF-8 leaf; no project was created")?
        .to_owned();
    validate_component(&name, INIT_NAME_MAX_BYTES)?;
    let requested_parent = absolute
        .parent()
        .ok_or("NJA040: an existing parent directory is required; no project was created")?
        .to_owned();
    let parent = existing_parent(&requested_parent)?;
    let target = parent.join(&name);
    check_path_budget(&target)?;
    for filename in FILENAMES {
        check_path_budget(&target.join(filename))?;
    }
    match fs::symlink_metadata(&target) {
        Ok(_) => return Err("NJA040: target already exists; existing files, directories and links are never reused or replaced".into()),
        Err(error) if error.kind() == io::ErrorKind::NotFound => {},
        Err(error) => return Err(io_failure("cannot inspect the requested new target", None, &error, false)),
    }
    Ok(Destination {
        requested_parent,
        parent,
        target,
        name,
    })
}

fn check_path_budget(path: &Path) -> Result<(), String> {
    let text = path
        .to_str()
        .ok_or("NJA040: project path must be valid UTF-8; no project was created")?;
    if text.len() > INIT_PATH_MAX_BYTES || path.components().count() > INIT_PATH_COMPONENT_LIMIT {
        return Err("NJA040: project and generated file paths must fit 32768 UTF-8 bytes and 128 components; no project was created".into());
    }
    Ok(())
}

fn check_components(path: &Path) -> Result<(), String> {
    for component in path.components() {
        match component {
            Component::ParentDir => {
                return Err(
                    "NJA040: parent traversal (..) is unsupported; no project was created".into(),
                );
            }
            Component::Prefix(prefix) => {
                #[cfg(windows)]
                if !path.is_absolute() {
                    return Err("NJA040: drive-relative paths are unsupported; use an ordinary relative path or an absolute local disk path".into());
                }
                #[cfg(windows)]
                if !matches!(
                    prefix.kind(),
                    std::path::Prefix::Disk(_) | std::path::Prefix::VerbatimDisk(_)
                ) {
                    return Err("NJA040: only local disk paths are supported; network/device namespaces are rejected".into());
                }
                #[cfg(not(windows))]
                let _ = prefix;
            }
            Component::Normal(name) => validate_component(
                name.to_str().ok_or(
                    "NJA040: project path components must be valid UTF-8; no project was created",
                )?,
                INIT_PARENT_COMPONENT_MAX_BYTES,
            )?,
            Component::RootDir | Component::CurDir => {}
        }
    }
    Ok(())
}

fn validate_component(name: &str, limit: usize) -> Result<(), String> {
    if name.is_empty() || name.len() > limit {
        return Err(format!(
            "NJA040: project component exceeds its nonempty {limit}-byte UTF-8 bound; no project was created"
        ));
    }
    let lower = name.to_ascii_lowercase();
    let stem = lower.split('.').next().unwrap_or("");
    let numbered_device = stem
        .strip_prefix("com")
        .or_else(|| stem.strip_prefix("lpt"))
        .is_some_and(|suffix| {
            matches!(
                suffix,
                "1" | "2" | "3" | "4" | "5" | "6" | "7" | "8" | "9" | "¹" | "²" | "³"
            )
        });
    if matches!(name, "." | "..")
        || lower == ".git"
        || matches!(stem, "con" | "prn" | "aux" | "nul")
        || numbered_device
        || name.ends_with(['.', ' '])
        || name.contains(['/', '\\', ':', '<', '>', '"', '|', '?', '*'])
        || name.chars().any(char::is_control)
    {
        return Err("NJA040: project names/components cannot contain traversal, private/device names, streams, reserved filename characters or controls; no project was created".into());
    }
    Ok(())
}

fn existing_parent(path: &Path) -> Result<PathBuf, String> {
    check_path_budget(path)?;
    check_components(path)?;
    let mut checked = PathBuf::new();
    for component in path.components() {
        match component {
            Component::CurDir => {}
            Component::ParentDir => {
                return Err(
                    "NJA040: parent traversal is unsupported; no project was created".into(),
                );
            }
            Component::Prefix(_) | Component::RootDir => checked.push(component.as_os_str()),
            Component::Normal(name) => {
                checked.push(name);
                let metadata = fs::symlink_metadata(&checked).map_err(|error| {
                    io_failure(
                        "parent must already exist as an ordinary directory",
                        None,
                        &error,
                        false,
                    )
                })?;
                ordinary_directory(&metadata)?;
            }
        }
    }
    ordinary_directory(&fs::symlink_metadata(&checked).map_err(|error| {
        io_failure("cannot inspect the parent directory", None, &error, false)
    })?)?;
    fs::canonicalize(&checked).map_err(|error| {
        io_failure(
            "cannot canonicalize the existing parent",
            None,
            &error,
            false,
        )
    })
}

fn ordinary_directory(metadata: &Metadata) -> Result<(), String> {
    #[cfg(windows)]
    let reparse = {
        use std::os::windows::fs::MetadataExt;
        metadata.file_attributes() & 0x400 != 0
    };
    #[cfg(not(windows))]
    let reparse = false;
    if metadata.file_type().is_symlink() || reparse {
        return Err(
            "NJA040: symlink/junction/reparse parent or target components are unsupported".into(),
        );
    }
    if !metadata.is_dir() {
        return Err("NJA040: parent and created target must be ordinary directories".into());
    }
    Ok(())
}

fn ensure_parent(destination: &Destination) -> Result<(), String> {
    if existing_parent(&destination.requested_parent)? != destination.parent {
        return Err(
            "NJA040: parent identity changed; stop and inspect the requested target".into(),
        );
    }
    Ok(())
}

fn ensure_owned_directory(destination: &Destination) -> Result<(), String> {
    ensure_parent(destination)?;
    ordinary_directory(&fs::symlink_metadata(&destination.target).map_err(|error| {
        io_failure("cannot inspect the created directory", None, &error, true)
    })?)?;
    if fs::canonicalize(&destination.target).map_err(|error| {
        io_failure(
            "cannot inspect created directory identity",
            None,
            &error,
            true,
        )
    })? != destination.target
    {
        return Err("NJA040: created directory identity changed; owned partial output was retained for inspection".into());
    }
    Ok(())
}

fn write_generated_files(destination: &Destination, generated: &Generated) -> Result<(), String> {
    for (filename, source) in FILENAMES.into_iter().zip(&generated.contents) {
        ensure_owned_directory(destination).map_err(partial_failure)?;
        let mut options = OpenOptions::new();
        options.write(true).create_new(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            options.mode(0o600);
        }
        let mut file = options
            .open(destination.target.join(filename))
            .map_err(|error| {
                io_failure(
                    "cannot exclusively create generated file",
                    Some(filename),
                    &error,
                    true,
                )
            })?;
        file.write_all(source.as_bytes())
            .and_then(|()| file.sync_all())
            .map_err(|error| {
                io_failure(
                    "cannot write/flush generated file",
                    Some(filename),
                    &error,
                    true,
                )
            })?;
    }
    ensure_owned_directory(destination).map_err(partial_failure)?;
    // File contents are flushed on every platform. Unix also permits this
    // directory flush; Windows inherits ACL/durability behavior without a claim
    // of directory-handle support or universal crash/power-loss durability.
    #[cfg(unix)]
    fs::File::open(&destination.target)
        .and_then(|directory| directory.sync_all())
        .map_err(|error| io_failure("cannot flush created directory", None, &error, true))?;
    Ok(())
}

fn partial_failure(message: String) -> String {
    format!("{message}; owned partial project output was retained for inspection")
}

fn io_failure(operation: &str, filename: Option<&str>, error: &io::Error, partial: bool) -> String {
    let file = filename.map_or_else(String::new, |name| format!(" {name}"));
    let system = error
        .raw_os_error()
        .map_or_else(String::new, |code| format!("; OS error {code}"));
    let retained = if partial {
        "; owned partial project output was retained for inspection"
    } else {
        ""
    };
    format!(
        "NJA040: {operation}{file}: {:?}{system}{retained}",
        error.kind()
    )
}

#[cfg(test)]
mod write_phase_tests {
    use super::*;
    #[test]
    fn exclusive_collision_retains_owned_partial_output_and_existing_content() {
        let temp = fs::canonicalize(std::env::temp_dir()).unwrap();
        let base = temp.join(format!("naja-scaffold-write-phase-{}", std::process::id()));
        fs::create_dir(&base).unwrap();
        let target = base.join("partial");
        let destination = destination(&target).unwrap();
        let generated = generate("partial").unwrap();
        fs::create_dir(&target).unwrap();
        fs::write(target.join("main.naja"), b"existing concurrent content").unwrap();
        let error = write_generated_files(&destination, &generated).unwrap_err();
        assert!(error.contains("owned partial project output was retained"));
        assert!(!error.contains(temp.to_str().unwrap()));
        assert_eq!(
            fs::read(target.join("main.naja")).unwrap(),
            b"existing concurrent content"
        );
        assert_eq!(
            fs::read_to_string(target.join("naja.toml")).unwrap(),
            generated.contents[0]
        );
        assert!(!target.join("test_smoke.naja").exists());
        assert!(
            init_project(&target)
                .unwrap_err()
                .contains("already exists")
        );
        let resolved = fs::canonicalize(&base).unwrap();
        assert!(
            resolved.parent() == Some(temp.as_path()),
            "Unsafe test cleanup parent"
        );
        assert!(
            resolved
                .file_name()
                .unwrap()
                .to_str()
                .unwrap()
                .starts_with("naja-scaffold-write-phase-")
        );
        fs::remove_dir_all(resolved).unwrap();
    }
}
