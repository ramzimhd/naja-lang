//! Native base-1e9 long division. One quotient/remainder computation is shared
//! by both operations. Candidate search is bounded to 30 trials per digit;
//! scratch is allocated once, never once per candidate or per quotient unit.
use super::{Ax, Bp, Bx, Code, Cx, Di, Dx, R8, R9, R10, R11, Runtime, Si, Sp};
use crate::hosted::runtime;

// Fixed kernel stack frame. RBP is restored before returning to source locals.
const A: i32 = -8;
const B: i32 = -16;
const N: i32 = -24;
const M: i32 = -32;
const Q: i32 = -40;
const R: i32 = -48;
const P: i32 = -56;
const ASIGN: i32 = -64;
const BSIGN: i32 = -72;
const INDEX: i32 = -80;
const LOW: i32 = -88;
const HIGH: i32 = -96;
const MID: i32 = -104;
const BASE: i32 = 1_000_000_000;

impl Runtime {
    pub(super) fn division(&self, c: &mut Code, integers: &runtime::Runtime) {
        let quotient = c.label();
        let remainder = c.label();
        let kernel = self.raw_divrem;
        let product = c.label();
        let compare = c.label();
        let subtract = c.label();
        let zero_divisor = c.label();
        let work_limit = c.label();
        c.bind(self.floor_divide);
        self.numeric_pair(c, quotient);
        c.bind(self.modulo);
        self.numeric_pair(c, remainder);
        c.bind(quotient);
        c.call(kernel);
        c.ret();
        c.bind(remainder);
        c.call(kernel);
        c.mov(Ax, Dx);
        c.ret();
        c.bind(kernel);
        c.push(Bp);
        c.mov(Bp, Sp);
        c.immediate(5, Sp, 128);
        c.store(Bp, A, Di);
        c.store(Bp, B, Si);
        c.load(Cx, Di, 8);
        c.store(Bp, N, Cx);
        c.load(Dx, Si, 8);
        c.store(Bp, M, Dx);
        c.immediate(7, Dx, 0);
        c.j(0x84, zero_divisor);
        let zero = c.label();
        let finish = c.label();
        let checked = c.label();
        c.immediate(7, Cx, 0);
        c.j(0x84, zero);
        // Counts originate in checked native integer objects; this explicit
        // upper bound keeps allocation size calculations safely below u64.
        c.immediate(7, Cx, (super::super::ARENA_BYTES / 4) as i32);
        c.j(0x87, integers.resource);
        c.immediate(7, Dx, (super::super::ARENA_BYTES / 4) as i32);
        c.j(0x87, integers.resource);
        c.immediate(7, Dx, 1);
        c.j(0x84, checked);
        // Check N <= floor(limit/M), avoiding overflow in N*M itself.
        c.mov(R8, Dx);
        c.imm(Ax, super::super::MAX_DIVISION_LIMB_PRODUCT as i64);
        c.zero(Dx);
        c.div(R8);
        c.cmp(Cx, Ax);
        c.j(0x87, work_limit);
        c.bind(checked);
        c.load(Dx, Di, 0);
        c.store(Bp, ASIGN, Dx);
        c.load(Dx, Si, 0);
        c.store(Bp, BSIGN, Dx);
        Self::division_buffer(c, integers, N, Q);
        Self::division_buffer(c, integers, M, R);
        c.load(Bx, Bp, Q);
        c.load(Cx, Bp, N);
        c.zero(Dx);
        c.put(Bx, Cx, Dx);
        // The remainder buffer always has M+1 initialized limbs. Full-width
        // shifts preserve zero padding and permit safe fixed-width comparison.
        c.load(Bx, Bp, R);
        c.load(Cx, Bp, M);
        c.step(Cx, false);
        let clear = c.label();
        c.bind(clear);
        c.step(Cx, true);
        c.put(Bx, Cx, Dx);
        c.immediate(7, Cx, 0);
        c.j(0x85, clear);
        c.load(Cx, Bp, N);
        c.store(Bp, INDEX, Cx);
        c.load(Cx, Bp, M);
        c.immediate(7, Cx, 1);
        let single = c.label();
        let general = c.label();
        let adjusted = c.label();
        c.j(0x84, single);
        Self::division_buffer(c, integers, M, P);
        c.bind(general);
        c.load(Cx, Bp, INDEX);
        c.immediate(7, Cx, 0);
        c.j(0x84, adjusted);
        c.step(Cx, true);
        c.store(Bp, INDEX, Cx);
        c.load(Bx, Bp, R);
        c.load(Cx, Bp, M);
        let shift = c.label();
        let shifted = c.label();
        c.bind(shift);
        c.mov(R8, Cx);
        c.step(R8, true);
        c.get(R9, Bx, R8);
        c.put(Bx, Cx, R9);
        c.step(Cx, true);
        c.j(0x85, shift);
        c.bind(shifted);
        c.load(Si, Bp, A);
        c.load(Cx, Bp, INDEX);
        c.get(Dx, Si, Cx);
        c.zero(Cx);
        c.put(Bx, Cx, Dx);
        // R < B means quotient digit zero; avoid 30 full candidate products
        // for every leading zero quotient digit of similarly sized operands.
        c.load(Cx, Bp, M);
        c.get(R8, Bx, Cx);
        c.immediate(7, R8, 0);
        let search = c.label();
        let digit_zero = c.label();
        let leading = c.label();
        c.j(0x85, search);
        c.load(Si, Bp, B);
        c.bind(leading);
        c.step(Cx, true);
        c.get(R8, Bx, Cx);
        c.get(R9, Si, Cx);
        c.cmp(R8, R9);
        c.j(0x82, digit_zero);
        c.j(0x87, search);
        c.immediate(7, Cx, 0);
        c.j(0x85, leading);
        c.bind(search);
        c.zero(Ax);
        c.store(Bp, LOW, Ax);
        c.imm(Ax, BASE as i64 - 1);
        c.store(Bp, HIGH, Ax);
        let search_loop = c.label();
        let found = c.label();
        let smaller = c.label();
        c.bind(search_loop);
        c.load(R8, Bp, LOW);
        c.load(R9, Bp, HIGH);
        c.cmp(R8, R9);
        c.j(0x84, found);
        c.mov(Ax, R8);
        c.add(Ax, R9);
        c.step(Ax, false);
        c.shift_right(Ax, 1);
        c.store(Bp, MID, Ax);
        c.call(product);
        c.call(compare);
        c.immediate(7, Ax, 0);
        c.j(0x8f, smaller);
        c.load(Ax, Bp, MID);
        c.store(Bp, LOW, Ax);
        c.jump(search_loop);
        c.bind(smaller);
        c.load(Ax, Bp, MID);
        c.step(Ax, true);
        c.store(Bp, HIGH, Ax);
        c.jump(search_loop);
        c.bind(found);
        c.load(Ax, Bp, LOW);
        c.store(Bp, MID, Ax);
        c.call(product);
        c.call(subtract);
        c.load(Dx, Bp, LOW);
        let store_digit = c.label();
        c.jump(store_digit);
        c.bind(digit_zero);
        c.zero(Dx);
        c.bind(store_digit);
        c.load(Bx, Bp, Q);
        c.load(Cx, Bp, INDEX);
        c.put(Bx, Cx, Dx);
        c.jump(general);

        c.bind(single);
        c.zero(R9);
        c.load(Si, Bp, B);
        c.zero(Cx);
        c.get(R11, Si, Cx);
        c.imm(R8, BASE as i64);
        let single_loop = c.label();
        let single_done = c.label();
        c.bind(single_loop);
        c.load(Cx, Bp, INDEX);
        c.immediate(7, Cx, 0);
        c.j(0x84, single_done);
        c.step(Cx, true);
        c.store(Bp, INDEX, Cx);
        c.load(Si, Bp, A);
        c.get(Ax, Si, Cx);
        c.mov(R10, R9);
        c.mul(R10, R8);
        c.add(Ax, R10);
        c.zero(Dx);
        c.div(R11);
        c.load(Bx, Bp, Q);
        c.put(Bx, Cx, Ax);
        c.mov(R9, Dx);
        c.jump(single_loop);
        c.bind(single_done);
        c.load(Bx, Bp, R);
        c.zero(Cx);
        c.put(Bx, Cx, R9);
        c.bind(adjusted);
        c.load(Ax, Bp, ASIGN);
        c.load(Dx, Bp, BSIGN);
        c.cmp(Ax, Dx);
        let signs = c.label();
        let nonzero_remainder = c.label();
        c.j(0x84, signs);
        c.load(Bx, Bp, R);
        c.load(Cx, Bp, M);
        c.step(Cx, false);
        let scan = c.label();
        c.bind(scan);
        c.step(Cx, true);
        c.get(R8, Bx, Cx);
        c.immediate(7, R8, 0);
        c.j(0x85, nonzero_remainder);
        c.immediate(7, Cx, 0);
        c.j(0x85, scan);
        c.jump(signs);
        c.bind(nonzero_remainder);
        // Different signs and a nonzero remainder: |q| += 1, |r| = |b|-|r|.
        c.load(Bx, Bp, Q);
        c.zero(Cx);
        c.load(R10, Bp, N);
        c.step(R10, false);
        let increment = c.label();
        let carry = c.label();
        let incremented = c.label();
        c.bind(increment);
        c.cmp(Cx, R10);
        c.j(0x83, integers.resource);
        c.get(R8, Bx, Cx);
        c.step(R8, false);
        c.immediate(7, R8, BASE);
        c.j(0x84, carry);
        c.put(Bx, Cx, R8);
        c.jump(incremented);
        c.bind(carry);
        c.zero(R8);
        c.put(Bx, Cx, R8);
        c.step(Cx, false);
        c.jump(increment);
        c.bind(incremented);
        c.load(Di, Bp, R);
        c.load(Si, Bp, B);
        c.zero(Cx);
        c.zero(R11);
        c.imm(R8, BASE as i64);
        let complement = c.label();
        let upper = c.label();
        let loaded = c.label();
        let no_borrow = c.label();
        let stored = c.label();
        c.bind(complement);
        c.load(R10, Bp, M);
        c.cmp(Cx, R10);
        c.j(0x84, upper);
        c.get(R9, Si, Cx);
        c.jump(loaded);
        c.bind(upper);
        c.zero(R9);
        c.bind(loaded);
        c.get(R10, Di, Cx);
        c.sub(R9, R10);
        c.sub(R9, R11);
        c.immediate(7, R9, 0);
        c.j(0x8d, no_borrow);
        c.add(R9, R8);
        c.imm(R11, 1);
        c.jump(stored);
        c.bind(no_borrow);
        c.zero(R11);
        c.bind(stored);
        c.put(Di, Cx, R9);
        c.step(Cx, false);
        c.load(R10, Bp, M);
        c.cmp(Cx, R10);
        c.j(0x86, complement);
        c.immediate(7, R11, 0);
        c.j(0x85, integers.resource);
        c.bind(signs);
        c.load(Bx, Bp, Q);
        c.load(R8, Bp, ASIGN);
        c.load(R9, Bp, BSIGN);
        c.mul(R8, R9);
        c.store(Bx, 0, R8);
        c.load(Bx, Bp, R);
        c.store(Bx, 0, R9);
        c.load(Bx, Bp, Q);
        c.call(integers.normalize);
        c.store(Bp, Q, Ax);
        c.load(Bx, Bp, R);
        c.call(integers.normalize);
        c.mov(Dx, Ax);
        c.load(Ax, Bp, Q);
        c.jump(finish);
        c.bind(zero);
        c.lea(Ax, integers.zero);
        c.mov(Dx, Ax);
        c.bind(finish);
        c.mov(Sp, Bp);
        c.pop(Bp);
        c.ret();

        c.bind(product);
        c.load(Bx, Bp, P);
        c.load(Si, Bp, B);
        c.load(Di, Bp, MID);
        c.zero(Cx);
        c.zero(R9);
        c.imm(R8, BASE as i64);
        let multiply = c.label();
        let multiplied = c.label();
        c.bind(multiply);
        c.load(R10, Bp, M);
        c.cmp(Cx, R10);
        c.j(0x84, multiplied);
        c.get(Ax, Si, Cx);
        c.mul(Ax, Di);
        c.add(Ax, R9);
        c.zero(Dx);
        c.div(R8);
        c.put(Bx, Cx, Dx);
        c.mov(R9, Ax);
        c.step(Cx, false);
        c.jump(multiply);
        c.bind(multiplied);
        c.put(Bx, Cx, R9);
        c.ret();
        c.bind(compare);
        c.load(Di, Bp, P);
        c.load(Si, Bp, R);
        c.load(Cx, Bp, M);
        c.step(Cx, false);
        let compare_loop = c.label();
        let positive = c.label();
        let negative = c.label();
        c.bind(compare_loop);
        c.step(Cx, true);
        c.get(R8, Di, Cx);
        c.get(R9, Si, Cx);
        c.cmp(R8, R9);
        c.j(0x87, positive);
        c.j(0x82, negative);
        c.immediate(7, Cx, 0);
        c.j(0x85, compare_loop);
        c.zero(Ax);
        c.ret();
        c.bind(positive);
        c.imm(Ax, 1);
        c.ret();
        c.bind(negative);
        c.imm(Ax, -1);
        c.ret();
        c.bind(subtract);
        c.load(Di, Bp, R);
        c.load(Si, Bp, P);
        c.zero(Cx);
        c.zero(R11);
        c.imm(R8, BASE as i64);
        let subtract_loop = c.label();
        let nonnegative = c.label();
        let sub_stored = c.label();
        c.bind(subtract_loop);
        c.get(R9, Di, Cx);
        c.get(R10, Si, Cx);
        c.sub(R9, R10);
        c.sub(R9, R11);
        c.immediate(7, R9, 0);
        c.j(0x8d, nonnegative);
        c.add(R9, R8);
        c.imm(R11, 1);
        c.jump(sub_stored);
        c.bind(nonnegative);
        c.zero(R11);
        c.bind(sub_stored);
        c.put(Di, Cx, R9);
        c.step(Cx, false);
        c.load(R10, Bp, M);
        c.cmp(Cx, R10);
        c.j(0x86, subtract_loop);
        c.immediate(7, R11, 0);
        c.j(0x85, integers.resource);
        c.ret();
        Self::division_error(c, zero_divisor, b"NJA206: integer division by zero\n", 106);
        Self::division_error(
            c,
            work_limit,
            b"NJA203: native division work limit exceeded\n",
            103,
        );
    }
    fn division_buffer(c: &mut Code, integers: &runtime::Runtime, count: i32, target: i32) {
        c.load(Ax, Bp, count);
        c.step(Ax, false);
        c.shift_left(Ax, 2);
        c.immediate(0, Ax, 16);
        c.call(integers.allocate);
        c.store(Bp, target, Ax);
        c.imm(Dx, 1);
        c.store(Ax, 0, Dx);
        c.load(Dx, Bp, count);
        c.step(Dx, false);
        c.store(Ax, 8, Dx);
    }
    pub(super) fn division_error(c: &mut Code, label: usize, message: &[u8], status: i64) {
        c.bind(label);
        let data = c.label();
        c.imm(Ax, 1);
        c.imm(Di, 2);
        c.lea(Si, data);
        c.imm(Dx, message.len() as i64);
        c.syscall();
        c.exit(status);
        c.bind(data);
        c.a.bytes(message);
    }
}
