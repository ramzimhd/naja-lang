from naja.numeric import rational, divide_exact, numerator, denominator

value = rational(6, -8)
print(numerator(value))
print(denominator(value))
value = rational(0, -123)
print(numerator(value))
print(denominator(value))
value = rational(True, True)
print(numerator(value))
print(denominator(value))
value = divide_exact(7, 3)
print(numerator(value))
print(denominator(value))
value = divide_exact(rational(1, 2), rational(3, 4))
print(numerator(value))
print(denominator(value))
value = rational(1, 2) * rational(2, 3) + rational(1, 4)
print(numerator(value))
print(denominator(value))
print(not rational(0, 1))
print(not rational(-1, 2))
print(rational(1, 1) == True)
print(rational(0, 1) == False)
print(rational(1, 3) < rational(1, 2))
print(2 > rational(3, 2) > True)
